
CREATE TABLE DONORS (
    DONOR_ID NUMBER PRIMARY KEY,
    DONOR_NAME VARCHAR2(50) NOT NULL,
    GENDER VARCHAR2(10),
    AGE NUMBER(3),
    BLOOD_GROUP VARCHAR2(5),
    PHONE VARCHAR2(15),
    CITY VARCHAR2(50),
    ADDRESS VARCHAR2(100)
);


CREATE SEQUENCE DONOR_SEQ START WITH 1 INCREMENT BY 1;

CREATE OR REPLACE TRIGGER DONOR_TRG
BEFORE INSERT ON DONORS
FOR EACH ROW
BEGIN
    IF :NEW.DONOR_ID IS NULL THEN
        SELECT DONOR_SEQ.NEXTVAL INTO :NEW.DONOR_ID
        FROM DUAL;
    END IF;
END;
/

CREATE TABLE INVENTORY (
    BLOOD_GROUP VARCHAR2(5) PRIMARY KEY,
    UNITS_AVAILABLE NUMBER DEFAULT 0 NOT NULL
);

CREATE TABLE BLOOD_REQUESTS (
    REQUEST_ID NUMBER PRIMARY KEY,
    PATIENT_NAME VARCHAR2(50) NOT NULL,
    BLOOD_GROUP VARCHAR2(5),
    UNITS_REQUIRED NUMBER,
    HOSPITAL_NAME VARCHAR2(100),
    REQUEST_DATE DATE DEFAULT SYSDATE,
    REQUEST_STATUS VARCHAR2(20)
);

CREATE SEQUENCE REQUEST_SEQ START WITH 1 INCREMENT BY 1;

CREATE OR REPLACE TRIGGER REQUEST_TRG
BEFORE INSERT ON BLOOD_REQUESTS
FOR EACH ROW
BEGIN
    IF :NEW.REQUEST_ID IS NULL THEN
        SELECT REQUEST_SEQ.NEXTVAL INTO :NEW.REQUEST_ID
        FROM DUAL;
    END IF;
END;
/

